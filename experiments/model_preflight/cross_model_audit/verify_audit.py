"""Bounded offline audit checks. No model, tokenizer, network or candidate inputs."""

import csv
import hashlib
import json
import platform
from pathlib import Path
import sys
from types import SimpleNamespace
import unicodedata

ROOT = Path(__file__).resolve().parent
WORKSPACE = ROOT.parents[2]
sys.path.insert(0, str(WORKSPACE))
sys.dont_write_bytecode = True

from harness.context_policy.protocol import completion


def sha(data):
    return hashlib.sha256(data).hexdigest()


def write_json(path, value):
    path.write_text(json.dumps(value, ensure_ascii=True, indent=2) + "\n", encoding="utf-8")


def main():
    assert platform.python_version() == "3.11.9"
    assert unicodedata.unidata_version == "14.0.0"
    manifest = json.loads((ROOT / "source_manifest.json").read_text(encoding="utf-8"))
    source_checks = []
    for entry in manifest["original_inputs"]:
        original = Path(entry["original_path"]).read_bytes()
        archive = (ROOT / entry["archived_path"]).read_bytes()
        assert original == archive
        assert len(archive) == entry["bytes"] and sha(archive) == entry["sha256"]
        source_checks.append({"id": entry["id"], "sha256": sha(archive), "unchanged": True})
    for entry in manifest["supplementary_inputs"]:
        data = (WORKSPACE / entry["path"]).read_bytes()
        assert len(data) == entry["bytes"] and sha(data) == entry["sha256"]

    # Existing hand-authored fixture, never generated by a model.
    fixtures = json.loads((WORKSPACE / "experiments/model_preflight/gpt_oss_20b/channel_parser_checks.json").read_text(encoding="utf-8"))
    fixture = next(f for f in fixtures if f["name"] == "analysis_then_final")
    assert fixture["hand_authored"] is True and fixture["model_generated"] is False
    assert fixture["total_tokens"] == len(fixture["token_ids"]) == 21
    assert fixture["token_ids"][-1] == fixture["terminal_token"] == 200002
    rendered = fixture["raw_rendered"]
    assert rendered.endswith("<|return|>")
    full = rendered[:-len("<|return|>")]
    final_message = next(m for m in fixture["parsed"] if m["channel"] == "final")
    final = "".join(c["text"] for c in final_message["content"])
    single = SimpleNamespace(targets=("synthetic.py",))
    multiple = SimpleNamespace(targets=("a.py", "b.py"))
    checks = []

    def parse(name, text, task=single, limit=False, integrity=True, tokens=21):
        result = completion(text, task, integrity_verified=integrity,
                            token_limit=limit, output_tokens=tokens,
                            finish_reason="length" if limit else "stop",
                            terminal_token_accounting={"synthetic": True, "verified_runtime": False})
        checks.append({"name": name, "category": result.category,
                       "artifacts": [list(a) for a in result.artifacts],
                       "raw_sha256": result.raw_sha256,
                       "normalized_sha256": result.normalized_sha256,
                       "diagnostics": list(result.diagnostics),
                       "model_generated": False})
        return result

    full_result = parse("full_rendered_stream_after_terminal_removal", full)
    final_result = parse("hypothetical_final_projection_not_authorized", final)
    assert full_result.artifacts == (("synthetic.py", full),)
    assert final_result.artifacts == (("synthetic.py", final),)
    assert full_result.normalized_sha256 != final_result.normalized_sha256
    assert "Synthetic reasoning." in full_result.artifacts[0][1]
    assert "Synthetic reasoning." not in final_result.artifacts[0][1]
    # Even an abstract transport that retains bodies while removing labels
    # cannot justify then removing substantive analysis. No join rule adopted.
    bodies_example = "Synthetic reasoning.\n" + final
    bodies_result = parse("illustrative_all_body_text_no_join_rule_adopted", bodies_example)
    assert bodies_result.artifacts[0][1] == bodies_example
    assert bodies_result.normalized_sha256 != final_result.normalized_sha256
    result = parse("bom_fence_and_whitespace_preserved", "\ufeff```python\r\nx=1\r```\r\n")
    assert result.artifacts == (("synthetic.py", "\ufeff```python\nx=1\n```\n"),)
    result = parse("single_empty", "", tokens=0)
    assert result.artifacts == (("synthetic.py", ""),)
    result = parse("multi_empty_final_section", "=== FILE: a.py ===\nx=1\n=== FILE: b.py ===\n", multiple)
    assert result.artifacts == (("a.py", "x=1\n"), ("b.py", ""))
    result = parse("substantive_preamble_multi", "Synthetic reasoning.\n=== FILE: a.py ===\nx=1\n=== FILE: b.py ===\n", multiple)
    assert result.category == "output_format_failure" and "first_header_not_zero" in result.diagnostics
    result = parse("cap_with_malformed_headers", "partial", multiple, limit=True, tokens=2048)
    assert result.category == "output_capacity_failure"
    result = parse("integrity_precedes_capacity", "partial", multiple, limit=True, integrity=False, tokens=2048)
    assert result.category == "infrastructure_invalid"
    result = parse("nul_rejected", "x\0")
    assert result.category == "output_format_failure"

    with (ROOT / "infrastructure_test_matrix.csv").open(encoding="utf-8", newline="") as stream:
        rows = list(csv.DictReader(stream))
    assert len(rows) == 38
    for model in ("Qwen3-Coder-30B-A3B", "Qwen3-Coder-Next"):
        assert [r["id"] for r in rows if r["model"] == model] == list("ABCDEFGHIJKLMNOPQRS")
    assert all(r["status"] == "NOT_RUN" for r in rows)
    report = (ROOT / "REPORT.md").read_text(encoding="utf-8")
    assert sum(line.startswith("## ") for line in report.splitlines()) == 17
    for entry in manifest["original_inputs"]:
        assert (ROOT / entry["archived_path"]).is_file()
    write_json(ROOT / "boundary_checks.json", {
        "status": "PASS", "python": platform.python_version(),
        "unicode": unicodedata.unidata_version,
        "scope": "local hand-authored parser examples; no inference, transport certification or full conformance",
        "source_checks": source_checks,
        "supplementary_inputs_unchanged": True,
        "parser_checks": checks,
        "matrix_rows": len(rows), "matrix_status": "all NOT_RUN",
        "report_sections": 17,
    })
    records = []
    for path in sorted(ROOT.rglob("*")):
        if path.is_file() and path.name != "artifact_manifest.json":
            data = path.read_bytes()
            records.append({"path": path.relative_to(ROOT).as_posix(), "bytes": len(data), "sha256": sha(data)})
    write_json(ROOT / "artifact_manifest.json", {
        "scope": "new cross_model_audit files only", "self_excluded": True,
        "signed": False, "files": records,
    })
    print(json.dumps({"status": "PASS", "source_copies": len(source_checks),
                      "parser_cases": len(checks), "matrix_rows": len(rows),
                      "artifact_files_in_manifest": len(records), "inference": False}))


if __name__ == "__main__":
    main()
